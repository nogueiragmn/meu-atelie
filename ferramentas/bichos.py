def olho(x, y, r=9):
    return c(x, y, r, PR) + brilho(x + r * 0.3, y - r * 0.35, r * 0.35)


def sorriso(x, y, w=18, h=12):
    return p(f'M{x - w} {y} Q{x} {y + h} {x + w} {y}')


